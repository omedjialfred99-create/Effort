CREATE TABLE IF NOT EXISTS specialites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS medecins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(100) NOT NULL,
  prenom VARCHAR(100) NOT NULL,
  specialite_id INTEGER NOT NULL REFERENCES specialites(id),
  telephone VARCHAR(20),
  photo_url VARCHAR(255),
  actif BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS patients (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(100) NOT NULL,
  prenom VARCHAR(100) NOT NULL,
  telephone VARCHAR(20) NOT NULL UNIQUE,
  email VARCHAR(150),
  date_naissance DATE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS personnel (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(100) NOT NULL,
  prenom VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'secretaire', 'medecin')),
  medecin_id INTEGER REFERENCES medecins(id),
  actif BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  personnel_id INTEGER NOT NULL REFERENCES personnel(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMP NOT NULL,
  used_at TIMESTAMP NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS disponibilites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medecin_id INTEGER NOT NULL REFERENCES medecins(id) ON DELETE CASCADE,
  jour_semaine SMALLINT NOT NULL,
  heure_debut TIME NOT NULL,
  heure_fin TIME NOT NULL
);

CREATE TABLE IF NOT EXISTS rendez_vous (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(10) NOT NULL UNIQUE,
  patient_id INTEGER NOT NULL REFERENCES patients(id),
  medecin_id INTEGER NOT NULL REFERENCES medecins(id),
  date_heure TIMESTAMP NOT NULL,
  duree_minutes INTEGER NOT NULL DEFAULT 30,
  motif TEXT,
  statut VARCHAR(20) DEFAULT 'en_attente'
    CHECK (statut IN ('en_attente', 'confirme', 'annule', 'termine')),
  origine VARCHAR(20) DEFAULT 'en_ligne'
    CHECK (origine IN ('en_ligne', 'presentiel')),
  present BOOLEAN DEFAULT FALSE,
  note_medecin TEXT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT no_double_booking UNIQUE (medecin_id, date_heure)
);
